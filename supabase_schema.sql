-- Run this in Supabase SQL Editor before deploying.
create table if not exists public.leads (
    id bigint generated by default as identity primary key,
    normalized_company_name text not null unique,
    company_name text not null,
    city text default '',
    state text default 'Maharashtra',
    website text default '',
    product_category text default '',
    business_type text default 'Unknown',
    phone text default '',
    email text default '',
    contact_name text default '',
    contact_role text default '',
    export_evidence text default '',
    expansion_signal text default '',
    alibaba_status text default 'Unknown',
    source_url text default '',
    product_fit integer not null default 0 check (product_fit between 0 and 100),
    export_readiness integer not null default 0 check (export_readiness between 0 and 100),
    expansion_score integer not null default 0 check (expansion_score between 0 and 100),
    alibaba_opportunity integer not null default 0 check (alibaba_opportunity between 0 and 100),
    contact_quality integer not null default 0 check (contact_quality between 0 and 100),
    total_score integer not null default 0,
    priority text default 'Research later',
    call_status text default 'Needs research',
    last_contacted text default '',
    next_action_date text default '',
    notes text default '',
    created_at text default '',
    updated_at text default ''
);

